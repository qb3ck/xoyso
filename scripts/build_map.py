"""Project the lon/lat sources in data-src/ into SVG path data (public/map-data.js).
Lambert conformal conic centred on Spain, Ramer-Douglas-Peucker simplification.
Usage: python3 scripts/build_map.py"""
import json, math

W = 1000  # viewBox width; height follows the bounding box
BBOX = (-9.8, 35.7, 4.6, 44.0)  # lon/lat window to show (peninsula + Balearics)

# Lambert conformal conic, standard parallels 37N / 43N, centre 40N 3.7W
phi1, phi2, phi0, lam0 = map(math.radians, (37, 43, 40, -3.7))
n = math.log(math.cos(phi1) / math.cos(phi2)) / math.log(math.tan(math.pi / 4 + phi2 / 2) / math.tan(math.pi / 4 + phi1 / 2))
F = math.cos(phi1) * math.tan(math.pi / 4 + phi1 / 2) ** n / n
rho0 = F / math.tan(math.pi / 4 + phi0 / 2) ** n
def lcc(lon, lat):
    lam, phi = math.radians(lon), math.radians(lat)
    rho = F / math.tan(math.pi / 4 + phi / 2) ** n
    return rho * math.sin(n * (lam - lam0)), rho0 - rho * math.cos(n * (lam - lam0))

# Fit the bounding window into the viewBox
corners = [lcc(x, y) for x in (BBOX[0], BBOX[2], (BBOX[0] + BBOX[2]) / 2) for y in (BBOX[1], BBOX[3])]
xmin, xmax = min(c[0] for c in corners), max(c[0] for c in corners)
ymin, ymax = min(c[1] for c in corners), max(c[1] for c in corners)
S = W / (xmax - xmin); H = round((ymax - ymin) * S)
def proj(lon, lat):
    x, y = lcc(lon, lat)
    return (x - xmin) * S, (ymax - y) * S

def rdp(pts, eps):
    if len(pts) < 3: return pts
    keep = [False] * len(pts); keep[0] = keep[-1] = True; stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop(); (ax, ay), (bx, by) = pts[a], pts[b]
        dx, dy = bx - ax, by - ay; L = math.hypot(dx, dy); best, bi = 0, -1
        for i in range(a + 1, b):
            if L < 1e-9:  # closed ring: measure distance from the start point
                d = math.hypot(pts[i][0] - ax, pts[i][1] - ay)
            else:
                d = abs(dy * (pts[i][0] - ax) - dx * (pts[i][1] - ay)) / L
            if d > best: best, bi = d, i
        if best > eps: keep[bi] = True; stack += [(a, bi), (bi, b)]
    return [p for p, k in zip(pts, keep) if k]

PAD = 60  # keep shapes a little beyond the viewBox so edges don't show
def inside(p): return -PAD <= p[0] <= W + PAD and -PAD <= p[1] <= H + PAD
def clip_ring(ring):
    # crude but fine: clamp points to the padded box (polygons only extend off-map at the edges)
    return [(min(max(x, -PAD), W + PAD), min(max(y, -PAD), H + PAD)) for x, y in ring]

def fmt(pts): return 'M' + 'L'.join(f'{x:.1f},{y:.1f}' for x, y in pts)

def poly_path(geom, eps):
    polys = geom['coordinates'] if geom['type'] == 'MultiPolygon' else [geom['coordinates']]
    out = []
    for poly in polys:
        for ring in poly:
            pts = [proj(*p) for p in ring]
            if not any(inside(p) for p in pts): continue
            pts = rdp(clip_ring(pts), eps)
            if len(pts) >= 4: out.append(fmt(pts) + 'Z')
    return ''.join(out)

def line_path(geom, eps):
    lines = geom['coordinates'] if geom['type'] == 'MultiLineString' else [geom['coordinates']]
    out, allpts = [], []
    for l in lines:
        pts = rdp([proj(*p) for p in l], eps)
        if len(pts) >= 2: out.append(fmt(pts)); allpts += pts
    return ''.join(out), allpts

def load(name): return json.load(open(f'data-src/{name}.geojson'))

land = load('land'); regions = load('regions'); rivers = load('rivers'); cities = load('cities')
out = {'width': W, 'height': H}
out['spain'] = ''.join(poly_path(f['geometry'], 0.35) for f in land['features'] if f['properties']['kind'] == 'spain')
out['neighbours'] = ''.join(poly_path(f['geometry'], 0.6) for f in land['features'] if f['properties']['kind'] != 'spain')
out['regions'] = ''.join(poly_path(f['geometry'], 0.5) for f in regions['features'])
out['countryLabels'] = [{'name': n, 'x': round(proj(*ll)[0]), 'y': round(proj(*ll)[1])} for n, ll in
                        [('PORTUGAL', (-8.0, 40.25)), ('FRANCIA', (0.6, 43.75)),
                         ('Océano Atlántico', (-9.3, 43.75)), ('Mar Mediterráneo', (2.6, 38.6)), ('Mar Cantábrico', (-5.0, 43.85))]]
# Quiz items, keyed 'topic:id'. kind: line (rivers), area (islands, ranges) or point (peaks)
out['items'] = {}
for f in rivers['features']:
    d, pts = line_path(f['geometry'], 0.25)
    xs = [p[0] for p in pts]; ys = [p[1] for p in pts]
    out['items']['rivers:' + f['properties']['id']] = {
        'kind': 'line', 'd': d, 'box': [round(min(xs)), round(min(ys)), round(max(xs)), round(max(ys))]}
out['cities'] = [{'name': f['properties']['name'], 'x': round(proj(*f['geometry']['coordinates'])[0], 1),
                  'y': round(proj(*f['geometry']['coordinates'])[1], 1)} for f in cities['features']]

js = '// Generated by scripts/build_map.py from data-src/ — do not edit by hand.\n' \
     '// Sources: SIANE (Instituto Geográfico Nacional, CC BY 4.0) via rOpenSpain/mapSpain; Natural Earth (public domain).\n' \
     'export const MAP = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n'
open('public/map-data.js', 'w').write(js)
print(f'viewBox 0 0 {W} {H}; {len(js) // 1024} KB')
for k, v in out['items'].items(): print(f'  {k:22} {v["kind"]:5} box {v["box"]}')
